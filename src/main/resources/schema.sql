CREATE TABLE IF NOT EXISTS app_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(32) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    created_at VARCHAR(40) NOT NULL
);

CREATE TABLE IF NOT EXISTS projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    departing_member VARCHAR(120) NOT NULL,
    created_by BIGINT NOT NULL REFERENCES app_accounts(id),
    created_at VARCHAR(40) NOT NULL
);

CREATE TABLE IF NOT EXISTS project_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id),
    account_id BIGINT NOT NULL REFERENCES app_accounts(id),
    member_role VARCHAR(20) NOT NULL CHECK (member_role IN ('COORDINATOR', 'RECIPIENT')),
    UNIQUE(project_id, account_id)
);

CREATE TABLE IF NOT EXISTS handover_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id),
    version_no INTEGER NOT NULL,
    created_by BIGINT NOT NULL REFERENCES app_accounts(id),
    request_token VARCHAR(36) NOT NULL,
    created_at VARCHAR(40) NOT NULL,
    snapshot_json TEXT NOT NULL,
    change_summary TEXT NOT NULL,
    UNIQUE(project_id, version_no),
    UNIQUE(project_id, request_token)
);

CREATE TABLE IF NOT EXISTS handover_acknowledgements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id BIGINT NOT NULL REFERENCES handover_versions(id),
    account_id BIGINT NOT NULL REFERENCES app_accounts(id),
    acknowledged_at VARCHAR(40) NOT NULL,
    UNIQUE(version_id, account_id)
);
